/**
 * Computes exact live unit-economics metrics at any settlement horizon T in [0h, 336h].
 */
export function computeWaterlineMetrics(
  tasks: WaterlineTask[],
  cutoffHours: number
): WaterlineMetricsAtCutoff {
  const n = Math.max(1, tasks.length);
  const clampedT = Math.min(MAX_HORIZON_HOURS, Math.max(0, cutoffHours));

  let tokenSum = 0;
  let surfacedCleanupSum = 0;
  let hiddenCleanupSum = 0;
  let cleanTasksCount = 0;
  let failedTasksTotal = 0;
  let surfacedFailuresCount = 0;

  for (const t of tasks) {
    tokenSum += t.tokenCostUsd;
    if (!t.failed) {
      cleanTasksCount++;
      continue;
    }
    failedTasksTotal++;
    if (t.discoveryHours <= clampedT) {
      surfacedFailuresCount++;
      surfacedCleanupSum += t.humanCleanupCostUsd;
    } else {
      hiddenCleanupSum += t.humanCleanupCostUsd;
    }
  }

  const avgTokenCostUsd = tokenSum / n;
  const avgSurfacedCleanupUsd = surfacedCleanupSum / n;
  const avgHiddenIbnrUsd = hiddenCleanupSum / n;
  const avgRealizedTotalUsd = avgTokenCostUsd + avgSurfacedCleanupUsd;
  const avgUltimateTotalUsd = avgTokenCostUsd + avgSurfacedCleanupUsd + avgHiddenIbnrUsd;

  const realizedMultiplier = avgRealizedTotalUsd / Math.max(0.0001, avgTokenCostUsd);
  const ultimateMultiplier = avgUltimateTotalUsd / Math.max(0.0001, avgTokenCostUsd);

  return {
    cutoffHours: clampedT,
    totalTasks: tasks.length,
    cleanTasksCount,
    failedTasksTotal,
    surfacedFailuresCount,
    hiddenFailuresCount: failedTasksTotal - surfacedFailuresCount,
    avgTokenCostUsd,
    avgSurfacedCleanupUsd,
    avgHiddenIbnrUsd,
    avgRealizedTotalUsd,
    avgUltimateTotalUsd,
    realizedMultiplier,
    ultimateMultiplier,
    apparentCleanPct: ((n - surfacedFailuresCount) / n) * 100,
    trueCleanPct: (cleanTasksCount / n) * 100,
    trueDefectPct: (failedTasksTotal / n) * 100,
  };
}
